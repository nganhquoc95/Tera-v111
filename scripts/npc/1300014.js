function start() {
	var player = cm.getPlayer();
	var quest2322 = cm.getQuestNoRecord(2322);
	var quest2322Data = quest2322 == null ? null : quest2322.getCustomData();
	if (quest2322 != null && quest2322.getStatus() == 1 &&
		(quest2322Data == null || parseInt(quest2322Data, 10) < 1)) {
		cm.sendOkS("Terrifying thorn vines grow on the towering city walls. How to enter the castle... Alas! Go back and tell #b#p1300003##k.", 3);
		quest2322.setCustomData("1");
		player.updateQuest(quest2322, true);
		return;
	}

	var quest2314 = cm.getQuestNoRecord(2314);
	var quest2314Data = quest2314 == null ? null : quest2314.getCustomData();
	if (quest2314 != null && quest2314.getStatus() == 1 &&
		(quest2314Data == null || parseInt(quest2314Data, 10) < 1)) {
		cm.sendNextS("This... seems to be a powerful magical barrier generated by some kind of mushroom spores. It should be impossible to break with physical force and attacks. Please go back and tell #b#p1300003##k.", 3);
		quest2314.setCustomData("1");
		player.updateQuest(quest2314, true);
		return;
	}

	cm.dispose();
}

function action(mode, type, selection) {
	if (mode > 0)
		cm.getClient().getSession().write(Packages.tools.packet.CField.EffectPacket.AranTutInstructionalBalloon("Effect/OnUserEff.img/normalEffect/mushroomcastle/chatBalloon1"));
	cm.dispose();
}